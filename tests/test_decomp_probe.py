def test_core_decomp_plan_passed_to_implement():
    """The plan generated by plan_fn must be passed as the last arg to implement_fn.

    - implement_fn is called twice: once for greedy (empty plan '') and once for
      decomp (with the plan from plan_fn).
    - plan_fn is called exactly once (for the decomp path only).
    """
    from harness.decomp_probe import _core_decomp_probe

    plan_calls: list[tuple] = []
    impl_plan_args: list[str] = []

    def stub_plan_fn(subject, name, parent_src, context, gherkin):
        plan = f"1. parse args\n2. iterate\n3. return result for {name}"
        plan_calls.append((subject, name))
        return plan

    def stub_implement_fn(subject, name, parent_src, context, gherkin, plan):
        impl_plan_args.append(plan)
        return f"def {name}():\n    pass\n"

    stub_oracle = _make_stub_oracle(pass_greedy=False, pass_decomp=True)

    with tempfile.TemporaryDirectory() as tmpdir:
        repo = Path(tmpdir)
        task, targets, orig, gherkins = _make_repo_and_task(repo)

        result = _core_decomp_probe(
            targets=targets,
            orig=orig,
            gherkins=gherkins,
            task=task,
            repo=repo,
            timeout=10,
            plan_fn=stub_plan_fn,
            implement_fn=stub_implement_fn,
            oracle_fn=stub_oracle,
        )

    # plan_fn called once (decomp path only, not greedy)
    assert len(plan_calls) == 1, f"expected 1 plan call, got {len(plan_calls)}"

    # implement_fn called twice: greedy (empty plan) + decomp (real plan)
    assert len(impl_plan_args) == 2, f"expected 2 implement calls, got {len(impl_plan_args)}"
    assert impl_plan_args[0] == "", "greedy call must pass empty plan"
    assert "parse args" in impl_plan_args[1], "decomp call must pass the plan text"

    # Scoring
    assert result["greedy_pass"] is False
    assert result["decomp_pass"] is True
    assert "skipped" not in result or result.get("skipped") is False


def test_core_decomp_oracle_is_score_only():
    """Oracle output must NOT influence plan_fn or implement_fn inputs.

    We verify by recording all plan_fn and implement_fn argument tuples and
    confirming none of them vary based on oracle outcomes.  An alternating oracle
    is used so any leakage would produce different args on different calls.
    """
    from harness.decomp_probe import _core_decomp_probe

    plan_args: list[tuple] = []
    impl_args: list[tuple] = []

    def recording_plan_fn(subject, name, parent_src, context, gherkin):
        plan_args.append((subject, name, gherkin))
        return "1. plan step"

    def recording_impl_fn(subject, name, parent_src, context, gherkin, plan):
        impl_args.append((subject, name, gherkin, plan))
        return f"def {name}():\n    pass\n"

    call_count: list[int] = [0]

    def alternating_oracle(repo, nodes, timeout):
        idx = call_count[0]
        call_count[0] += 1
        return set() if idx % 2 == 0 else set(nodes)

    with tempfile.TemporaryDirectory() as tmpdir:
        repo = Path(tmpdir)
        task, targets, orig, gherkins = _make_repo_and_task(repo)

        _core_decomp_probe(
            targets=targets,
            orig=orig,
            gherkins=gherkins,
            task=task,
            repo=repo,
            timeout=10,
            plan_fn=recording_plan_fn,
            implement_fn=recording_impl_fn,
            oracle_fn=alternating_oracle,
        )

    # plan_fn called once only (decomp, not greedy)
    assert len(plan_args) == 1

    # implement_fn called twice: greedy + decomp
    assert len(impl_args) == 2

    # subject, name, gherkin must be identical across both implement calls
    assert impl_args[0][0] == impl_args[1][0], "subject must be identical"
    assert impl_args[0][1] == impl_args[1][1], "name must be identical"
    assert impl_args[0][2] == impl_args[1][2], "gherkin must be identical (oracle must not feed back)"


