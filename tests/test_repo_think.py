class _FakeLlm:
    def complete(self, request) -> _FakeCompletion:
        return _FakeCompletion("def stub():\n    pass\n")


# ---------------------------------------------------------------------------
# Fake agent factory — emits a code.write_file Decision with fixed content
# ---------------------------------------------------------------------------

def _make_stub_agent(content: str, path_key: str = "code_path"):
    from jaros.core import create_decision

    class _StubAgent:
        def decide(self, ctx) -> list:
            path = (ctx.get("spec_path") or ctx.get("test_path")
                    or ctx.get("code_path") or ".jcode/stub.out")
            return [create_decision(
                id=f"stub-{uuid.uuid4().hex}", source="stub-agent",
                type="code.write_file",
                payload={"path": path, "content": content},
            )]
    return _StubAgent()


# The direct code generated by the first code_agent call.
_DIRECT_CODE = "def foo(x):\n    return x + 1\n"
# The think-regenerated code (what _g_code_think returns in the "fires" case).
_THINK_CODE  = "def foo(x):\n    return x\n"

# A parent_src with a docstring example (used when testing with examples).
_PARENT_WITH_EXAMPLES = (
    "def foo(x):\n"
    "    '''Return x.\n"
    "    >>> foo(0)\n"
    "    0\n"
    "    '''\n"
    "    return x\n"
)

# A parent_src with NO docstring examples.
_PARENT_NO_EXAMPLES = "def foo(x):\n    return x\n"


