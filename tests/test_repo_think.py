# ---------------------------------------------------------------------------
# (a) think=True + examples + direct fails -> think fires
# ---------------------------------------------------------------------------

def test_think_fires_when_examples_fail(tmp_path: Path):
    """Gate: examples exist AND direct code fails them -> _g_code_think called once."""
    from harness.behavioral_solve import behavioral_solve_jaros
    import harness.jaros_solve_ops as _ops

    agents, spec_p, test_p, code_p = _agent_sequence(tmp_path)
    rt = _make_runtime(tmp_path)

    think_call_args = []

    def _fake_g_code_think(subject, name, parent_src, context, gherkin):
        think_call_args.append((subject, name))
        return _THINK_CODE

    with patch("harness.behavioral_solve._load_agent_from_file",
               side_effect=_make_load_agent(agents)), \
         patch.object(_ops, "run_tests", side_effect=_make_run_tests_ok()), \
         patch("harness.pass1_eval._doctest_asserts",
               return_value=[("foo(0)", "0")]), \
         patch("harness.pass1_eval._visible_ok",
               return_value=False), \
         patch("harness.commit_replay._g_code_think",
               side_effect=_fake_g_code_think) as mock_think:

        result = behavioral_solve_jaros(
            intent="implement foo",
            name="foo",
            current_src=_PARENT_WITH_EXAMPLES,
            context="",
            pkg="pkg",
            runtime=rt,
            llm=_FakeLlm(),
            spec_path=spec_p,
            test_path=test_p,
            code_path=code_p,
            think=True,
        )

    # _g_code_think must have been called exactly once
    assert mock_think.call_count == 1, (
        f"Expected _g_code_think to be called once; got {mock_think.call_count}"
    )
    # The result code must be the think-regenerated code
    assert result["code"] == _THINK_CODE, (
        f"Expected think-regenerated code; got {result['code']!r}"
    )


