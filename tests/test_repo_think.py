def _make_runtime(tmp_path: Path):
    from harness.coding_loop import Runtime
    return Runtime(data_dir=tmp_path)


# ---------------------------------------------------------------------------
# Shared agent index: gherkin=0, test=1, code=2
# ---------------------------------------------------------------------------

def _agent_sequence(tmp_path: Path):
    """Return [gherkin_agent, test_agent, code_agent] stubs."""
    spec_p = str(tmp_path / "spec.gherkin")
    test_p = str(tmp_path / "test_foo.py")
    code_p = str(tmp_path / "foo.py")
    gherkin_a = _make_stub_agent("1. Given foo(0) returns 0\n")
    test_a    = _make_stub_agent("from pkg import foo\ndef test_it():\n    assert foo(0)==0\n")
    code_a    = _make_stub_agent(_DIRECT_CODE)
    return [gherkin_a, test_a, code_a], spec_p, test_p, code_p


def _make_load_agent(agents: list):
    idx = [0]
    def _load(filepath, llm):
        a = agents[idx[0] % len(agents)]
        idx[0] += 1
        return a
    return _load


def _make_run_tests_ok():
    """Fake run_tests that always returns exit 0."""
    from jaros.core import create_decision

    def _rt(rt_, command, *, cwd=None, timeout_s=15, source=""):
        d = create_decision(
            id=f"sh-{uuid.uuid4().hex}", source="test",
            type="shell.exec",
            payload={"command": command},
        )
        res = rt_.apply(d)
        if isinstance(res, dict):
            res["exitCode"] = 0
        return res if isinstance(res, dict) else {"exitCode": 0, "stdout": "1 passed", "stderr": ""}
    return _rt


