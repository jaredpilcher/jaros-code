"""EXT-018: gated-thinking on the repo code grain (--think flag).

Unit tests — all offline. No Jetson, no subprocess, no repo checkout.
Patches: _load_agent_from_file (agents), jaros_solve_ops.run_tests (Docker),
         harness.pass1_eval._doctest_asserts + _visible_ok (gate helpers),
         harness.commit_replay._g_code_think (think-regeneration stub).

Coverage:
  (a) think=True + current_src has examples + direct code FAILS them
       -> _g_code_think called exactly once, returned code used
  (b) think=True + current_src has examples + direct code PASSES them
       -> _g_code_think NOT called (gate kept direct)
  (c) think=True + current_src has NO examples
       -> _g_code_think NOT called (nothing to gate on)
  (d) think=False (default) + examples that would fail
       -> _g_code_think NOT called (default path byte-identical)
  (e) ast.parse + import smoke on behavioral_solve.py
  (f) _g_code_think defined in commit_replay with correct signature
"""
