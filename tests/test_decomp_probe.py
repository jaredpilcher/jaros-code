def _make_repo_and_task(tmpdir: Path):
    """Create a minimal repo structure and task dict for offline testing."""
    (tmpdir / "pkg").mkdir(exist_ok=True)
    cf = "pkg/mod.py"
    (tmpdir / cf).write_text("def foo():\n    pass\n", encoding="utf-8")
    task = {
        "sha": "abc12345" * 5,
        "parent": "p" * 40,
        "subject": "add foo behaviour",
        "redgreen": ["tests/test_mod.py::test_foo"],
        "code_files": [cf],
        "test_files": ["tests/test_mod.py"],
        "repo": "pkg",
    }
    targets = [(cf, "foo", "def foo():\n    pass\n")]
    orig = {cf: "def foo():\n    pass\n"}
    gherkins = {(cf, "foo"): "Given foo called\nThen it returns None"}
    return task, targets, orig, gherkins


def _make_stub_oracle(pass_greedy: bool = False, pass_decomp: bool = True):
    """Return a stub oracle.

    Call index 0 is the greedy (no-plan) baseline; index 1 is the decomp attempt.
    This matches the order in _core_decomp_probe (greedy first, decomp second).
    """
    call_count: list[int] = [0]

    def oracle(repo, nodes, timeout):
        idx = call_count[0]
        call_count[0] += 1
        if idx == 0:
            return set() if pass_greedy else set(nodes)
        else:
            return set() if pass_decomp else set(nodes)

    oracle.call_count = call_count
    return oracle


