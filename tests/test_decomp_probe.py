def test_core_decomp_oracle_call_order():
    """Oracle is called exactly twice: first for greedy, then for decomp."""
    from harness.decomp_probe import _core_decomp_probe

    oracle_call_args: list[tuple] = []

    def recording_oracle(repo, nodes, timeout):
        oracle_call_args.append((list(nodes), timeout))
        return set(nodes)  # always fail

    with tempfile.TemporaryDirectory() as tmpdir:
        repo = Path(tmpdir)
        task, targets, orig, gherkins = _make_repo_and_task(repo)

        _core_decomp_probe(
            targets=targets,
            orig=orig,
            gherkins=gherkins,
            task=task,
            repo=repo,
            timeout=10,
            plan_fn=lambda *_: "1. plan",
            implement_fn=lambda s, n, *_: f"def {n}():\n    pass\n",
            oracle_fn=recording_oracle,
        )

    # Oracle must be called exactly twice: greedy + decomp
    assert len(oracle_call_args) == 2, f"expected 2 oracle calls, got {len(oracle_call_args)}"
    # Both calls use the same redgreen nodes
    assert oracle_call_args[0][0] == oracle_call_args[1][0], "both calls use the same nodes"
